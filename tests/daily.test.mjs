import test from 'node:test';
import assert from 'node:assert/strict';
import {initialState,saveAnimal} from '../dist/core.mjs';
import {dailyTables,saveDaily,automaticDaily,utcDay} from '../dist/daily.mjs';
const date='2026-10-07',stamp=date+'T12:00:00Z',seed=()=>({...initialState(date),dailyRecords:[],automaticStarted:date,settings:{autoDaily:true}});
test('daily tables isolate effective-date events and present stock',()=>{
 const s=seed(),a=s.animals[0],tables=dailyTables([...s.animals,{...a,id:'arrival',arrived:date},{...a,id:'departure',departed:date},{...a,id:'archived',archived:true}],date);
 assert.deepEqual(tables.births.map(a=>a.id),['DEMO-016']);assert.equal(tables.deaths.length,0);
 assert.ok(tables.stock.some(a=>a.id==='arrival'));assert.ok(!tables.stock.some(a=>['departure','archived','DEMO-014','DEMO-015'].includes(a.id)));
});
test('same-day replacement preserves prior capture and increments one published set',()=>{
 let s=saveDaily(seed(),{at:stamp,actor:'Tester'}),first=structuredClone(s.dailyRecords[0]);
 s=saveAnimal(s,{...s.animals[0],notes:'Later change'},'Tester',date+'T13:00:00Z',s.animals[0].id);
 s=saveDaily(s,{at:date+'T14:00:00Z',actor:'Tester'});assert.equal(s.dailyRecords.length,1);assert.equal(s.dailyRecords[0].revision,2);
 assert.equal(s.events.at(-1).dailyBefore.animals[0].notes,first.animals[0].notes);assert.equal(s.dailyRecords[0].animals[0].notes,'Later change');
});
test('past daily records cannot be manually changed or generated by arbitrary automatic backdating',()=>{
 const s=saveDaily(seed(),{at:stamp});assert.throws(()=>saveDaily(s,{at:'2026-10-08T01:00:00Z',date}),/final/);
 assert.throws(()=>saveDaily(s,{at:'2026-10-09T01:00:00Z',source:'automatic',date}),/yesterday/);
});
test('frozen CSV copies preserve hidden field data and original headings',()=>{
 const s=seed();s.columns[0].label='Original sex';s.columns[0].visible=false;
 const next=saveDaily(s,{at:stamp}),rec=next.dailyRecords[0];s.columns[0].label='Renamed';s.animals[0].sex='Changed';
 assert.ok(rec.csv.stock.includes('Original sex'));assert.ok(rec.csv.stock.includes('Male'));assert.ok(!rec.csv.stock.includes('Renamed'));assert.ok(rec.rows.births.length>1);assert.equal(rec.rows.deaths.length,1);
});
test('automatic fallback uses yesterday history rather than todays modified animals',()=>{
 let s=seed();const originalRoom=s.animals[0].room;
 s=saveAnimal(s,{...s.animals[0],room:'Room B',cage:'B-01'},'Tester','2026-10-08T00:10:00Z',s.animals[0].id);
 s=automaticDaily(s,'2026-10-08T00:20:00Z');assert.equal(s.dailyRecords[0].date,date);assert.equal(s.dailyRecords[0].source,'automatic');assert.equal(s.dailyRecords[0].animals[0].room,originalRoom);
});
test('automatic generation respects manual precedence, disable setting and tracking start',()=>{
 const s=saveDaily(seed(),{at:stamp});assert.deepEqual(automaticDaily(s,'2026-10-08T00:05:00Z').dailyRecords,s.dailyRecords);
 const disabled=seed();disabled.settings.autoDaily=false;assert.equal(automaticDaily(disabled,'2026-10-08T00:05:00Z').dailyRecords.length,0);
 assert.equal(automaticDaily(seed(),stamp).dailyRecords.length,0);
});
test('automatic generation does not invent an unavailable baseline',()=>{
 const s=seed();s.events=[];assert.equal(automaticDaily(s,'2026-10-08T00:05:00Z').dailyRecords.length,0);
});
test('automatic capture reconstructs field definitions from before next-day configuration',()=>{
 const s=seed(),before=structuredClone(s.columns);s.columns[0].label='New heading';s.events.push({id:'schema',at:'2026-10-08T00:01:00Z',schemaBefore:{columns:before},schemaAfter:{columns:s.columns},snapshot:structuredClone(s.animals)});
 const n=automaticDaily(s,'2026-10-08T00:05:00Z');assert.equal(n.dailyRecords[0].columns[0].label,before[0].label);
});
test('UTC reporting day handles local offset at midnight',()=>{assert.equal(utcDay('2026-10-07T23:30:00-02:00'),'2026-10-08');});